def parse_db_url(url):
    from urllib.parse import urlparse, unquote
    r = urlparse(url)
    return {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": unquote(r.path.lstrip("/")),
        "USER": unquote(r.username) if r.username else "",
        "PASSWORD": unquote(r.password) if r.password else "",
        "HOST": r.hostname,
        "PORT": str(r.port or 5432),
    }

DATABASES = {"default": parse_db_url(DATABASE_URL)}

